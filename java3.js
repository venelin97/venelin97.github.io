function renderEvents() {
  const container = document.getElementById("events");
  const epochEvents = eventsData[currentEpoch] || [];
  const query = eventSearch.value.trim().toLocaleLowerCase("bg");
  const matchingEvents = epochEvents
    .map((event, index) => ({ event, index, key: `${currentEpoch}:${index}` }))
    .filter(({ event, key }) => {
      const matchesSearch = !query ||
        `${event.title} ${event.text} ${Object.values(event.details).join(" ")}`.toLocaleLowerCase("bg").includes(query);
      return matchesSearch && (!showSavedEvents || savedEvents.has(key));
    });

  container.replaceChildren();
  container.dataset.count = String(matchingEvents.length);
  matchingEvents.forEach(({ event, key }) => {
    const card = document.createElement("article");
    card.className = "event-card";

    const openButton = document.createElement("button");
    openButton.type = "button";
    openButton.className = "event-open";
    openButton.setAttribute("aria-label", `Прочети: ${event.title.trim()}`);

    const image = document.createElement("img");
    image.className = "event-card-image";
    image.src = event.image;
    image.alt = "";
    image.loading = "lazy";

    const title = document.createElement("span");
    title.className = "event-card-title";
    title.textContent = event.title.trim();
    const summary = document.createElement("span");
    summary.className = "event-card-summary";
    summary.textContent = event.text.trim().split(/(?<=[.!?])\s+(?=[А-Я„“])/u)[0] || event.text;
    openButton.append(image, title, summary);
    openButton.addEventListener("click", () => openOverlay(event));

    const imageCredit = createImageCredit(event.image, "event-image-credit");
    const saveButton = document.createElement("button");
    const isSaved = savedEvents.has(key);
    saveButton.type = "button";
    saveButton.className = "event-save";
    saveButton.textContent = isSaved ? "♥" : "♡";
    saveButton.setAttribute("aria-pressed", String(isSaved));
    saveButton.setAttribute("aria-label", isSaved
      ? `Премахни от запазени: ${event.title.trim()}`
      : `Запази: ${event.title.trim()}`);
    saveButton.addEventListener("click", () => {
      if (savedEvents.has(key)) savedEvents.delete(key);
      else savedEvents.add(key);
      persistSavedEvents();
      renderEvents();
    });

    card.append(openButton);
    if (imageCredit) card.append(imageCredit);
    card.append(saveButton);
    container.appendChild(card);
  });

  if (matchingEvents.length === 0) {
    const emptyMessage = document.createElement("p");
    emptyMessage.className = "empty-events";
    emptyMessage.textContent = showSavedEvents
      ? savedEvents.size === 0
        ? "Още нямаш запазени събития. Натисни сърцето върху събитие, за да го добавиш тук."
        : "Няма запазени събития от тази епоха."
      : "Няма събития, които да отговарят на търсенето.";
    container.appendChild(emptyMessage);
  }

  savedEventsCount.textContent = String(savedEvents.size);
  savedEventsButton.setAttribute("aria-pressed", String(showSavedEvents));
  eventsStatus.textContent = `${matchingEvents.length} от ${epochEvents.length} събития${savedEvents.size ? ` · ${savedEvents.size} запазени` : ""}${savedEventsStorageWarning ? ` · ${savedEventsStorageWarning}` : ""}`;
}

