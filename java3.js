function createImageCredit(imagePath, className = "image-credit") {
  const credit = historicalImageCredits[imagePath];
  if (!credit) return null;

  const element = document.createElement("span");
  element.className = className;
  element.append(document.createTextNode(`${credit.credit} · `));

  for (const [label, href] of [
    [credit.sourceLabel, credit.source],
    [credit.license, credit.licenseUrl]
  ]) {
    const link = document.createElement("a");
    link.href = href;
    link.target = "_blank";
    link.rel = "noopener noreferrer";
    link.textContent = label;
    element.append(link);
    if (label === credit.sourceLabel) element.append(document.createTextNode(" · "));
  }

  return element;
}


