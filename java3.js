function findLearningEvents(topic) {
  const normalizedTopic = topic.toLocaleLowerCase("bg");
  const words = normalizedTopic.match(/[\p{L}\d]{4,}/gu) || [];
  const ignoredWords = new Set(["това", "което", "какво", "какви", "когато", "кога", "защо", "българска", "български", "история"]);
  const keywords = words.filter(word => !ignoredWords.has(word));
  if (!keywords.length) return [];

  return allHistoricalEvents
    .map(event => ({
      event,
      relevance: keywords.reduce((score, keyword) =>
        score + (`${event.title} ${event.text}`.toLocaleLowerCase("bg").includes(keyword) ? 1 : 0), 0)
    }))
    .filter(result => result.relevance > 0)
    .sort((first, second) => second.relevance - first.relevance)
    .slice(0, 8)
    .map(result => result.event);
}

function createTopicQuiz(events) {
  return shuffle(events).map(event => {
    const clue = event.text.trim().split(/[.!?](?:\s|$)/)[0].slice(0, 190);
    const distractors = shuffle(allHistoricalEvents
      .filter(candidate => candidate !== event)
      .map(candidate => candidate.title.trim()))
      .filter(candidate => candidate !== event.title.trim())
      .slice(0, 3);
    const correct = event.title.trim();
    return {
      q: `Кое събитие описва този откъс?\n„${clue}${clue.length === 190 ? "…" : ""}“`,
      correct,
      options: shuffle([correct, ...distractors])
    };
  });
}

