function flipMemoryCard(card, cardData) {
  if (memoryLocked || memoryMatched.has(cardData.pairId) || card.classList.contains("flipped")) return;
  card.classList.add("flipped");
  const faceLabel = cardData.face === "image" ? "Снимка" : "Събитие";
  card.setAttribute("aria-label", `${faceLabel}: ${cardData.event.title.trim()}`);
  memorySelection.push({ card, cardData });
  if (memorySelection.length !== 2) return;

  const [first, second] = memorySelection;
  if (first.cardData.pairId === second.cardData.pairId) {
    memoryMatched.add(first.cardData.pairId);
    first.card.classList.add("matched");
    second.card.classList.add("matched");
    memorySelection = [];
    memoryScore.textContent = `${memoryMatched.size} / 6 двойки${memoryMatched.size === 6 ? " · Браво!" : ""}`;
    return;
  }

  memoryLocked = true;
  memoryFlipTimeout = window.setTimeout(() => {
    first.card.classList.remove("flipped");
    second.card.classList.remove("flipped");
    first.card.setAttribute("aria-label", "Обърни карта");
    second.card.setAttribute("aria-label", "Обърни карта");
    memorySelection = [];
    memoryLocked = false;
    memoryFlipTimeout = null;
  }, 850);
}

