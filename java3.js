function renderChronology(showResults = false) {
  const list = document.getElementById("order-list");
  list.replaceChildren();

  const sortedMilestones = [...chronologyMilestones].sort((a, b) => a.year - b.year);

  chronologyOrder.forEach((milestone, index) => {
    const row = document.createElement("li");
    row.className = "order-card";

    const isCorrect = showResults && sortedMilestones[index].year === milestone.year;
    if (showResults) {
      row.classList.add(isCorrect ? "order-correct" : "order-wrong");
    }

    const badge = document.createElement("span");
    badge.className = "order-badge";
    badge.textContent = String(index + 1);

    const image = document.createElement("img");
    image.src = milestone.image;
    image.alt = "";
    image.loading = "lazy";

    const details = document.createElement("div");
    details.className = "order-card-details";

    const title = document.createElement("span");
    title.className = "order-card-title";
    title.textContent = milestone.title;
    details.appendChild(title);

    if (showResults) {
      const yearSpan = document.createElement("span");
      yearSpan.className = "order-card-year";
      yearSpan.textContent = isCorrect
        ? `✓ ${milestone.yearText}`
        : `✗ Трябва да е другаде (Година: ${milestone.yearText})`;
      details.appendChild(yearSpan);
    }

    const controls = document.createElement("div");
    controls.className = "order-card-controls";

    for (const [direction, label, offset] of [
      ["up", "Премести нагоре", -1],
      ["down", "Премести надолу", 1]
    ]) {
      const moveButton = document.createElement("button");
      moveButton.type = "button";
      moveButton.className = "order-move";
      moveButton.textContent = direction === "up" ? "↑" : "↓";
      moveButton.setAttribute("aria-label", `${label}: ${milestone.title}`);
      moveButton.disabled = index + offset < 0 || index + offset >= chronologyOrder.length;
      moveButton.addEventListener("click", () => {
        const newIndex = index + offset;
        [chronologyOrder[index], chronologyOrder[newIndex]] =
          [chronologyOrder[newIndex], chronologyOrder[index]];
        renderChronology(false);
      });
      controls.appendChild(moveButton);
    }

    row.append(badge, image, details, controls);
    list.appendChild(row);
  });
}

