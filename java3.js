function updateQuizProgress() {
  if (!currentQuizSelection.length) return;
  const answered = document.querySelectorAll("#questions-container input:checked").length;
  const progressText = document.getElementById("quiz-progress-text");
  progressText.textContent = `${answered} от ${currentQuizSelection.length} отговорени`;
  document.getElementById("quiz-progress-fill").style.width =
    `${Math.round(answered / currentQuizSelection.length * 100)}%`;
}

function updateQuizTimer() {
  const remaining = Math.max(0, selectedQuizMode.seconds - Math.floor((Date.now() - quizStartedAt) / 1000));
  const minutes = String(Math.floor(remaining / 60)).padStart(2, "0");
  const seconds = String(remaining % 60).padStart(2, "0");
  quizTimer.textContent = `${minutes}:${seconds}`;
  quizTimer.classList.toggle("urgent", remaining <= 10);
  if (remaining === 0) checkQuiz();
}

function updateQuizBest(score) {
  const key = `bulgarian-history-quiz-best-${selectedQuizMode.count}-${selectedQuizMode.seconds}`;
  let best = 0;
  try {
    const storedBest = localStorage.getItem(key);
    if (storedBest !== null) {
      best = Number(storedBest);
      if (!Number.isInteger(best) || best < 0 || best > selectedQuizMode.count) {
        throw new TypeError("Запазеният резултат от теста е невалиден.");
      }
    }
    if (typeof score === "number" && score > best) {
      best = score;
      localStorage.setItem(key, String(score));
    }
  } catch (error) {
    console.error("Грешка при зареждане или запис на най-добрия резултат.", error);
  }

  document.getElementById("quiz-best").textContent =
    best ? `${best} / ${selectedQuizMode.count}` : "—";
}

function checkQuiz() {
  if (!currentQuizSelection.length || quizFinished) return;
  quizFinished = true;
  window.clearInterval(quizTimerInterval);
  quizModeButtons.forEach(button => { button.disabled = false; });

  let score = 0;
  currentQuizSelection.forEach((question, questionIndex) => {
    const options = document.getElementsByName(`q${questionIndex}`);
    options.forEach(option => {
      const row = option.closest(".answer-option");
      const icon = row.querySelector(".status-icon");
      option.disabled = true;
      if (option.value === question.correct) {
        row.classList.add("correct");
        icon.textContent = "✓";
      } else if (option.checked) {
        row.classList.add("wrong");
        icon.textContent = "×";
      }
      if (option.checked && option.value === question.correct) score++;
    });
  });

  checkButton.style.display = "none";
  updateQuizProgress();
  showQuizResult(score);
}

function showQuizResult(score) {
  updateQuizBest(score);
  document.getElementById("quiz-score").textContent =
    `${score} / ${currentQuizSelection.length}`;
  const message = score === currentQuizSelection.length
    ? "Блестящо! Познаваш историята в детайл."
    : score >= Math.ceil(currentQuizSelection.length * 0.7)
      ? "Чудесен резултат! Още няколко открития и ще знаеш още повече."
      : score >= Math.ceil(currentQuizSelection.length * 0.4)
        ? topicQuizPool
          ? `Добро начало. Върни се към темата „${topicQuizLabel}“ и опитай отново.`
          : "Добро начало. Разгледай времевата линия и опитай отново."
        : topicQuizPool
          ? `Всяко голямо пътешествие започва с първа стъпка. Прегледай „${topicQuizLabel}“ и опитай пак!`
          : "Всяко голямо пътешествие започва с първа стъпка. Опитай пак!";
  document.getElementById("quiz-result-message").textContent = message;
  document.getElementById("quiz-result-overlay").style.display = "flex";
  document.body.style.overflow = "hidden";
}

