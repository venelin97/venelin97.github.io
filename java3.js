function showMapPlace(placeId) {
  const place = mapPlaces[placeId];
  if (!place) return;

  document.querySelectorAll(".map-place-button").forEach(button => {
    const isActive = button.dataset.mapPlace === placeId;
    button.classList.toggle("active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  const bboxValue = place.bbox || `${place.longitude - 0.08},${place.latitude - 0.05},${place.longitude + 0.08},${place.latitude + 0.05}`;
  const mapParameters = new URLSearchParams({
    bbox: bboxValue,
    layer: "mapnik",
    marker: `${place.latitude},${place.longitude}`
  });
  document.getElementById("history-map-frame").src =
    `https://www.openstreetmap.org/export/embed.html?${mapParameters}`;
  const mapLink = new URL("https://www.openstreetmap.org/");
  mapLink.searchParams.set("mlat", String(place.latitude));
  mapLink.searchParams.set("mlon", String(place.longitude));
  mapLink.hash = `map=13/${place.latitude}/${place.longitude}`;
  document.getElementById("map-attribution").href = mapLink.toString();

  const story = document.getElementById("map-story");
  story.replaceChildren();
  const kicker = document.createElement("p");
  kicker.className = "section-kicker";
  kicker.textContent = "Историческо място";
  const heading = document.createElement("h4");
  heading.textContent = place.name;
  const description = document.createElement("p");
  description.textContent = place.detail;
  const relatedEvent = allHistoricalEvents.find(event =>
    event.title.trim().toLocaleLowerCase("bg").includes(place.event.toLocaleLowerCase("bg"))
  ) || allHistoricalEvents.find(event =>
    place.event.toLocaleLowerCase("bg").includes(event.title.trim().toLocaleLowerCase("bg"))
  );
  const openButton = document.createElement("button");
  openButton.type = "button";
  openButton.className = "map-story-link";
  openButton.textContent = relatedEvent ? `Прочети: ${relatedEvent.title.trim()} →` : "Разгледай времевата линия →";
  openButton.addEventListener("click", () => {
    if (relatedEvent) openOverlay(relatedEvent);
    else showSection("line");
  });
  story.append(kicker, heading, description, openButton);
}

